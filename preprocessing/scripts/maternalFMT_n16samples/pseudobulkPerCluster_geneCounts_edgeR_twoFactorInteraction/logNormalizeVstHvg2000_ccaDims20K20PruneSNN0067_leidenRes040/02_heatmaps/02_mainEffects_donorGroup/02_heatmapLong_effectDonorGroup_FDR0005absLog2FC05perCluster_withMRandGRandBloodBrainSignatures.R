find_donor_group_test_id <- function(test_definitions) {

  required_columns <- c(
    "test_id",
    "sheet_name",
    "comparison"
  )

  missing_columns <- setdiff(
    required_columns,
    colnames(test_definitions)
  )

  if (length(missing_columns) > 0L) {
    stop(
      "Test-definition table is missing: ",
      paste(missing_columns, collapse = ", "),
      call. = FALSE
    )
  }

  test_table <- test_definitions |>
    dplyr::mutate(
      test_id_chr = as.character(.data$test_id),
      sheet_name_chr = as.character(.data$sheet_name),
      comparison_chr = as.character(.data$comparison),
      test_id_lower = tolower(.data$test_id_chr),
      sheet_name_lower = tolower(.data$sheet_name_chr),
      comparison_lower = tolower(.data$comparison_chr)
    )

  # Hard exclusions:
  # donor-group main effect must not be a sex test or interaction test.
  eligible_rows <- test_table |>
    dplyr::filter(
      !grepl("interaction", .data$test_id_lower),
      !grepl("interaction", .data$sheet_name_lower),
      !grepl("sex", .data$test_id_lower),
      !grepl("sex", .data$sheet_name_lower),
      !grepl("male", .data$test_id_lower),
      !grepl("male", .data$sheet_name_lower),
      !grepl("female", .data$test_id_lower),
      !grepl("female", .data$sheet_name_lower),
      !grepl("simple", .data$test_id_lower),
      !grepl("simple", .data$sheet_name_lower)
    )

  # Score only information that is specific enough to identify the main
  # donor-group effect. Importantly, the word "donor" in comparison text alone
  # is NOT sufficient because sex comparisons may contain phrases such as
  # "averaged equally across donor groups".
  scored_rows <- eligible_rows |>
    dplyr::mutate(
      donor_test_score =
        5L * (
          grepl("donor", .data$test_id_lower) |
          grepl("fmt", .data$test_id_lower)
        ) +
        4L * (
          grepl("donor", .data$sheet_name_lower) |
          grepl("fmt", .data$sheet_name_lower)
        ) +
        3L * grepl("group", .data$test_id_lower) +
        2L * grepl("group", .data$sheet_name_lower) +
        3L * (
          grepl("asd", .data$comparison_lower) &
          grepl("neurotypical", .data$comparison_lower)
        ) +
        1L * (
          grepl("asd", .data$test_id_lower) |
          grepl("neurotypical", .data$test_id_lower)
        ) +
        5L * (
          grepl("overall", .data$test_id_lower) |
          grepl("overall", .data$sheet_name_lower)
        )
    ) |>
    dplyr::filter(.data$donor_test_score > 0L)

  if (nrow(scored_rows) == 0L) {
    message("\nAll available edgeR test definitions:")
    print(
      test_definitions |>
        dplyr::select(
          .data$test_id,
          .data$sheet_name,
          .data$comparison
        ),
      n = Inf
    )

    stop(
      "Could not identify any donor-group main-effect candidate.",
      call. = FALSE
    )
  }

  best_score <- max(scored_rows$donor_test_score)

  best_rows <- scored_rows |>
    dplyr::filter(
      .data$donor_test_score == best_score
    )

  if (nrow(best_rows) != 1L) {
    message("\nBest donor-group test candidates:")
    print(
      best_rows |>
        dplyr::select(
          .data$test_id,
          .data$sheet_name,
          .data$comparison,
          .data$donor_test_score
        ),
      n = Inf
    )

    message("\nAll available edgeR test definitions:")
    print(
      test_definitions |>
        dplyr::select(
          .data$test_id,
          .data$sheet_name,
          .data$comparison
        ),
      n = Inf
    )

    stop(
      "Could not uniquely identify the donor-group main-effect test. ",
      "Best-score candidates found: ",
      nrow(best_rows),
      call. = FALSE
    )
  }

  selected_test_id <- as.character(best_rows$test_id[[1]])

  # Final safety check.
  selected_test_id_lower <- tolower(selected_test_id)
  selected_sheet_lower <- tolower(as.character(best_rows$sheet_name[[1]]))

  if (
    grepl("sex", selected_test_id_lower) ||
    grepl("sex", selected_sheet_lower) ||
    grepl("interaction", selected_test_id_lower) ||
    grepl("interaction", selected_sheet_lower)
  ) {
    stop(
      "Internal safety check failed: selected donor-group test appears to be ",
      "a sex or interaction test: ",
      selected_test_id,
      call. = FALSE
    )
  }

  selected_test_id
}


calculate_row_zscores <- function(
  expression_matrix,
  lower_limit = -2,
  upper_limit = 2
) {

  output_matrix <- matrix(
    NA_real_,
    nrow = nrow(expression_matrix),
    ncol = ncol(expression_matrix),
    dimnames = dimnames(expression_matrix)
  )

  for (row_index in seq_len(nrow(expression_matrix))) {

    values <- as.numeric(expression_matrix[row_index, ])
    finite_values <- is.finite(values)

    if (sum(finite_values) < 2L) {
      output_matrix[row_index, finite_values] <- 0
      next
    }

    row_mean <- mean(values[finite_values])
    row_sd <- stats::sd(values[finite_values])

    if (!is.finite(row_sd) || row_sd == 0) {
      output_matrix[row_index, finite_values] <- 0
      next
    }

    output_matrix[row_index, finite_values] <-
      (values[finite_values] - row_mean) / row_sd
  }

  output_matrix[
    is.finite(output_matrix) &
      output_matrix < lower_limit
  ] <- lower_limit

  output_matrix[
    is.finite(output_matrix) &
      output_matrix > upper_limit
  ] <- upper_limit

  output_matrix
}


modified_correlation_distance <- function(
  expression_matrix,
  cluster_labels,
  base_distance = "2 - r",
  r_scale = 1,
  same_cluster_bonus = 0.20
) {

  if (!is.matrix(expression_matrix)) {
    expression_matrix <- as.matrix(expression_matrix)
  }

  if (nrow(expression_matrix) <= 1L) {
    return(
      stats::as.dist(
        matrix(
          0,
          nrow = 1,
          ncol = 1
        )
      )
    )
  }

  cluster_labels <- as.character(cluster_labels)

  if (length(cluster_labels) != nrow(expression_matrix)) {
    stop(
      "The number of cluster labels must equal the number of heatmap rows.",
      call. = FALSE
    )
  }

  if (!is.numeric(r_scale) || length(r_scale) != 1L || !is.finite(r_scale)) {
    stop(
      "`r_scale` must be one finite numeric value.",
      call. = FALSE
    )
  }

  if (
    !is.numeric(same_cluster_bonus) ||
    length(same_cluster_bonus) != 1L ||
    !is.finite(same_cluster_bonus) ||
    same_cluster_bonus < 0 ||
    same_cluster_bonus >= 1
  ) {
    stop(
      "`same_cluster_bonus` must be a finite number in [0, 1).",
      call. = FALSE
    )
  }

  cor_mat <- suppressWarnings(
    stats::cor(
      t(expression_matrix),
      method = "pearson",
      use = "pairwise.complete.obs"
    )
  )

  cor_mat[!is.finite(cor_mat)] <- 0
  diag(cor_mat) <- 1

  base_dist <- if (identical(base_distance, "2 - r")) {
    2 - (cor_mat * r_scale)
  } else if (identical(base_distance, "1 - r")) {
    1 - (cor_mat * r_scale)
  } else {
    stop(
      "`base_distance` must be either '2 - r' or '1 - r'.",
      call. = FALSE
    )
  }

  same_cluster_matrix <- outer(
    cluster_labels,
    cluster_labels,
    FUN = "=="
  )

  dist_mat <- base_dist

  dist_mat[same_cluster_matrix] <-
    base_dist[same_cluster_matrix] * (1 - same_cluster_bonus)

  dist_mat[!same_cluster_matrix] <-
    base_dist[!same_cluster_matrix] * (1 + same_cluster_bonus)

  diag(dist_mat) <- 0
  dist_mat[dist_mat < 0] <- 0

  stats::as.dist(dist_mat)
}


create_modified_row_hclust <- function(
  expression_matrix,
  annotation_table,
  base_distance = "2 - r",
  r_scale = 1,
  same_cluster_bonus = 0.20,
  linkage_method = "complete"
) {

  matched_annotation <- annotation_table[
    match(
      rownames(expression_matrix),
      annotation_table$row_id
    ),
    ,
    drop = FALSE
  ]

  if (
    nrow(matched_annotation) != nrow(expression_matrix) ||
    anyNA(matched_annotation$row_id) ||
    anyNA(matched_annotation$cluster_id)
  ) {
    stop(
      "Failed to match source-cluster annotations to all heatmap rows.",
      call. = FALSE
    )
  }

  modified_distance <- modified_correlation_distance(
    expression_matrix = expression_matrix,
    cluster_labels = matched_annotation$cluster_id,
    base_distance = base_distance,
    r_scale = r_scale,
    same_cluster_bonus = same_cluster_bonus
  )

  stats::hclust(
    modified_distance,
    method = linkage_method
  )
}


