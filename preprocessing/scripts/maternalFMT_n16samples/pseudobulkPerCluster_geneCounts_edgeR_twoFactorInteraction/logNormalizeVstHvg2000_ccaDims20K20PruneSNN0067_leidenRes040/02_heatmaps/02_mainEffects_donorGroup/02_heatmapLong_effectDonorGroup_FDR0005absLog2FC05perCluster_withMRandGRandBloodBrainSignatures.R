p_value_to_marker <- function(p_value) {

  if (length(p_value) != 1L || is.na(p_value) || !is.finite(p_value)) {
    return("")
  }

  if (p_value < 0.001) {
    return("***")
  }

  if (p_value < 0.01) {
    return("**")
  }

  if (p_value < 0.05) {
    return("*")
  }

  ""
}


format_p_value <- function(p_value) {

  if (length(p_value) != 1L || is.na(p_value) || !is.finite(p_value)) {
    return("NA")
  }

  if (p_value < 0.001) {
    return(
      format(
        p_value,
        scientific = TRUE,
        digits = 3
      )
    )
  }

  formatC(
    p_value,
    format = "f",
    digits = 4
  )
}


run_fisher_target_enrichment <- function(
  foreground_genes,
  target_genes,
  test_set_label,
  background_size = 19437L
) {

  foreground_genes <- unique(
    toupper(
      trimws(
        as.character(
          foreground_genes
        )
      )
    )
  )

  target_genes <- unique(
    toupper(
      trimws(
        as.character(
          target_genes
        )
      )
    )
  )

  foreground_genes <- foreground_genes[
    !is.na(foreground_genes) &
      foreground_genes != ""
  ]

  target_genes <- target_genes[
    !is.na(target_genes) &
      target_genes != ""
  ]

  n_foreground_genes <- length(
    foreground_genes
  )

  n_target_genes <- length(
    target_genes
  )

  overlap_genes <- sort(
    intersect(
      foreground_genes,
      target_genes
    )
  )

  n_overlap_genes <- length(
    overlap_genes
  )

  if (n_foreground_genes > background_size) {
    stop(
      "Foreground contains ",
      n_foreground_genes,
      " unique genes, exceeding Fisher background size ",
      background_size,
      ".",
      call. = FALSE
    )
  }

  if (n_target_genes > background_size) {
    stop(
      test_set_label,
      " target union contains ",
      n_target_genes,
      " genes, exceeding Fisher background size ",
      background_size,
      ".",
      call. = FALSE
    )
  }

  # 2 x 2 contingency table:
  #
  #                         TF target     Not TF target
  #   Foreground                a               b
  #   Background remainder     c               d
  #
  # Total universe is fixed to background_size = 19,437.
  contingency_a <- n_overlap_genes
  contingency_b <- n_foreground_genes - contingency_a
  contingency_c <- n_target_genes - contingency_a
  contingency_d <- background_size -
    contingency_a -
    contingency_b -
    contingency_c

  if (
    contingency_a < 0L ||
    contingency_b < 0L ||
    contingency_c < 0L ||
    contingency_d < 0L
  ) {
    stop(
      "Invalid Fisher contingency table for ",
      test_set_label,
      ": a=",
      contingency_a,
      ", b=",
      contingency_b,
      ", c=",
      contingency_c,
      ", d=",
      contingency_d,
      ", background_size=",
      background_size,
      ".",
      call. = FALSE
    )
  }

  fisher_matrix <- matrix(
    c(
      contingency_a,
      contingency_b,
      contingency_c,
      contingency_d
    ),
    nrow = 2,
    byrow = TRUE,
    dimnames = list(
      set = c(
        "Foreground",
        "Background_remainder"
      ),
      target = c(
        "TF_target",
        "Not_TF_target"
      )
    )
  )

  test_is_defined <-
    n_foreground_genes > 0L &&
    n_target_genes > 0L &&
    (background_size - n_target_genes) > 0L

  if (isTRUE(test_is_defined)) {

    fisher_test <- stats::fisher.test(
      fisher_matrix,
      alternative = "greater"
    )

    p_value <- fisher_test$p.value

    odds_ratio <- if (
      length(fisher_test$estimate) == 1L
    ) {
      as.numeric(
        fisher_test$estimate[[1]]
      )
    } else {
      NA_real_
    }

  } else {

    p_value <- NA_real_
    odds_ratio <- NA_real_
  }

  tibble::tibble(
    test_set = test_set_label,
    background_size = as.integer(
      background_size
    ),
    n_foreground_genes = n_foreground_genes,
    n_test_set_genes = n_target_genes,
    n_overlap_genes = n_overlap_genes,
    odds_ratio = odds_ratio,
    p_value = p_value,
    significance_marker = p_value_to_marker(
      p_value
    ),
    overlap_genes = if (
      n_overlap_genes > 0L
    ) {
      paste(
        overlap_genes,
        collapse = "|"
      )
    } else {
      ""
    }
  )
}


make_repetition_annotation <- function(
  values,
  fill_colours,
  font_size,
  width_mm = 4.5
) {

  values <- as.integer(
    values
  )

  labels <- as.character(
    values
  )

  text_colours <- ifelse(
    values >= max(
      values,
      na.rm = TRUE
    ) &
      values > 1,
    "white",
    "black"
  )

  ComplexHeatmap::AnnotationFunction(
    which = "row",

    width = grid::unit(
      width_mm,
      "mm"
    ),

    var_import = list(
      annotation_values = values,
      annotation_labels = labels,
      annotation_text_colours = text_colours,
      annotation_fill_colours = fill_colours,
      annotation_font_size = font_size
    ),

    fun = function(index) {

      n_current <- length(
        index
      )

      y_positions <- 1 - (
        seq_len(
          n_current
        ) -
          0.5
      ) /
        n_current

      current_values <- annotation_values[
        index
      ]

      current_labels <- annotation_labels[
        index
      ]

      current_text_colours <-
        annotation_text_colours[
          index
        ]

      current_fill <- unname(
        annotation_fill_colours[
          as.character(
            current_values
          )
        ]
      )

      current_fill[
        is.na(
          current_fill
        )
      ] <- marker_absent_colour

      grid::grid.rect(
        x = grid::unit(
          0.5,
          "npc"
        ),

        y = grid::unit(
          y_positions,
          "npc"
        ),

        width = grid::unit(
          1,
          "npc"
        ),

        height = grid::unit(
          1 / n_current,
          "npc"
        ),

        gp = grid::gpar(
          fill = current_fill,
          col = NA
        )
      )

      grid::grid.text(
        label = current_labels,

        x = grid::unit(
          0.5,
          "npc"
        ),

        y = grid::unit(
          y_positions,
          "npc"
        ),

        gp = grid::gpar(
          col = current_text_colours,
          fontsize = annotation_font_size,
          fontface = "bold"
        )
      )
    }
  )
}


