# ==============================================================================
# 16. Function generating one heatmap variant
# ==============================================================================

generate_heatmap_variant <- function(
  file_index,
  variant_id,
  max_mean_percent_threshold,
  filter_label
) {

  message("\n")
  message(
    paste(
      rep(
        "=",
        78
      ),
      collapse = ""
    )
  )

  message(
    "Generating heatmap variant: ",
    variant_id
  )

  message(
    "Max mean % filter: ",
    filter_label
  )

  if (is.na(max_mean_percent_threshold)) {

    significant_current <- significant_donor_group_base

  } else {

    significant_current <- significant_donor_group_base |>
      dplyr::filter(
        !is.na(.data$max_mean_percent),
        .data$max_mean_percent >= max_mean_percent_threshold
      )
  }

  if (nrow(significant_current) == 0L) {
    stop(
      "Heatmap variant '",
      variant_id,
      "' contains zero rows after applying Max mean % filter ",
      filter_label,
      ".",
      call. = FALSE
    )
  }

  fisher_foreground_genes <- unique(
    significant_current$gene_symbol_upper
  )

  fisher_global_current <- dplyr::bind_rows(
    lapply(
      fisher_test_set_order,
      function(test_set_current) {

        run_fisher_target_enrichment(
          foreground_genes = fisher_foreground_genes,
          target_genes = fisher_test_sets[[test_set_current]],
          test_set_label = test_set_current,
          background_size = fisher_background_size
        )
      }
    )
  ) |>
    dplyr::mutate(
      variant_order = file_index,
      variant_id = variant_id,
      max_mean_percent_threshold = max_mean_percent_threshold,
      max_mean_percent_filter = filter_label,
      cluster_id = NA_integer_,
      anatomical_region = NA_character_,
      .before = 1
    )

  gr_fisher <- fisher_global_current |>
    dplyr::filter(
      .data$test_set == "GR"
    )

  mr_fisher <- fisher_global_current |>
    dplyr::filter(
      .data$test_set == "MR"
    )

  if (
    nrow(gr_fisher) != 1L ||
    nrow(mr_fisher) != 1L
  ) {
    stop(
      "Could not uniquely retrieve global GR/MR Fisher results.",
      call. = FALSE
    )
  }

  gr_fisher_p <- gr_fisher$p_value[[1]]
  mr_fisher_p <- mr_fisher$p_value[[1]]

  gr_fisher_marker <- gr_fisher$significance_marker[[1]]
  mr_fisher_marker <- mr_fisher$significance_marker[[1]]

  all_cluster_ids_for_fisher <- names(
    custom_cluster_labels
  )

  fisher_per_cluster_current <- dplyr::bind_rows(
    lapply(
      all_cluster_ids_for_fisher,
      function(cluster_id_current) {

        cluster_foreground_genes <- unique(
          significant_current$gene_symbol_upper[
            significant_current$cluster_id == cluster_id_current
          ]
        )

        dplyr::bind_rows(
          lapply(
            fisher_test_set_order,
            function(test_set_current) {

              run_fisher_target_enrichment(
                foreground_genes = cluster_foreground_genes,
                target_genes = fisher_test_sets[[test_set_current]],
                test_set_label = test_set_current,
                background_size = fisher_background_size
              )
            }
          )
        ) |>
          dplyr::mutate(
            variant_order = file_index,
            variant_id = variant_id,
            max_mean_percent_threshold = max_mean_percent_threshold,
            max_mean_percent_filter = filter_label,
            cluster_id = as.integer(
              cluster_id_current
            ),
            anatomical_region = unname(
              custom_cluster_labels[
                cluster_id_current
              ]
            ),
            .before = 1
          )
      }
    )
  ) |>
    dplyr::group_by(
      .data$variant_id
    ) |>
    dplyr::mutate(
      FDR_BH = stats::p.adjust(
        .data$p_value,
        method = "BH"
      ),

      FDR_significance_marker = dplyr::case_when(
        !is.na(.data$FDR_BH) &
          .data$FDR_BH < 0.001 ~ "***",
        !is.na(.data$FDR_BH) &
          .data$FDR_BH < 0.01 ~ "**",
        !is.na(.data$FDR_BH) &
          .data$FDR_BH < 0.05 ~ "*",
        TRUE ~ ""
      )
    ) |>
    dplyr::ungroup() |>
    dplyr::select(
      .data$variant_order,
      .data$variant_id,
      .data$max_mean_percent_threshold,
      .data$max_mean_percent_filter,
      .data$cluster_id,
      .data$anatomical_region,
      .data$test_set,
      .data$background_size,
      .data$n_foreground_genes,
      .data$n_test_set_genes,
      .data$n_overlap_genes,
      .data$odds_ratio,
      .data$p_value,
      .data$significance_marker,
      .data$FDR_BH,
      .data$FDR_significance_marker,
      .data$overlap_genes
    )

  # Recalculate the number of clusters containing each gene specifically
  # for the currently displayed heatmap.
  significant_current <- significant_current |>
    dplyr::group_by(.data$ensembl_gene_id) |>
    dplyr::mutate(
      n_clusters_for_gene = dplyr::n_distinct(.data$cluster_id)
    ) |>
    dplyr::ungroup()

  current_row_ids <- significant_current$row_id

  sample_level_cpm_matrix_current <- sample_level_cpm_matrix_base[
    current_row_ids,
    ,
    drop = FALSE
  ]

  number_missing_values <- sum(
    is.na(
      sample_level_cpm_matrix_current
    )
  )

  log2_cpm_matrix_current <- log2(
    sample_level_cpm_matrix_current + 1
  )

  # Row-wise Z-scores are recalculated independently for every variant.
  zscore_matrix_current <- calculate_row_zscores(
    expression_matrix = log2_cpm_matrix_current,
    lower_limit = zscore_lower_limit,
    upper_limit = zscore_upper_limit
  )

  row_annotation_table <- significant_current |>
    dplyr::transmute(
      row_id = .data$row_id,
      cluster_id = .data$cluster_id,

      cluster_label = vapply(
        .data$cluster_id,
        format_cluster_label,
        FUN.VALUE = character(1)
      ),

      logFC = .data$logFC,
      abs_logFC = .data$abs_logFC,
      PValue = .data$PValue,
      FDR = .data$FDR,
      max_mean_percent = .data$max_mean_percent,
      fdr_symbol = .data$fdr_symbol,
      log2fc_symbol = .data$log2fc_symbol,
      n_clusters_for_gene = .data$n_clusters_for_gene
    )

  # Recalculate clustering independently for the current filtered heatmap.
  if (nrow(zscore_matrix_current) > 1L) {

    hc_rows <- create_modified_row_hclust(
      expression_matrix = zscore_matrix_current,
      annotation_table = row_annotation_table,
      base_distance = row_clustering_base_distance,
      r_scale = row_clustering_r_scale,
      same_cluster_bonus = row_clustering_same_cluster_bonus,
      linkage_method = row_clustering_linkage_method
    )

    cluster_rows_current <- hc_rows
    row_dend_reorder_current <- row_annotation_table$logFC

  } else {

    cluster_rows_current <- FALSE
    row_dend_reorder_current <- FALSE
  }

  cluster_factor_levels <- as.character(
    sort(
      unique(
        as.integer(
          row_annotation_table$cluster_id
        )
      )
    )
  )

  cluster_annotation_colors <- custom_cluster_colors[
    cluster_factor_levels
  ]

  names(
    cluster_annotation_colors
  ) <- cluster_factor_levels

  # Number of displayed cluster-gene results per cluster in this exact variant.
  cluster_result_counts <- table(
    factor(
      row_annotation_table$cluster_id,
      levels = cluster_factor_levels
    )
  )

  cluster_legend_labels <- paste0(
    "C",
    cluster_factor_levels,
    " (n = ",
    as.integer(cluster_result_counts),
    "): ",
    unname(
      custom_cluster_labels[
        cluster_factor_levels
      ]
    )
  )

  number_of_results <- nrow(
    significant_current
  )

  number_of_unique_genes <- length(
    unique(
      significant_current$ensembl_gene_id
    )
  )

  number_of_clusters <- length(
    cluster_factor_levels
  )

  number_of_samples <- ncol(
    zscore_matrix_current
  )

  annotation_row_font_size <- if (number_of_results <= 100L) {
    7.0
  } else if (number_of_results <= 300L) {
    5.6
  } else if (number_of_results <= 700L) {
    4.4
  } else {
    3.6
  }

  percent_annotation_labels <- ifelse(
    is.na(
      row_annotation_table$max_mean_percent
    ),
    "NA",
    paste0(
      round(
        row_annotation_table$max_mean_percent
      ),
      "%"
    )
  )

  percent_annotation_text_colour <- ifelse(
    !is.na(
      row_annotation_table$max_mean_percent
    ) &
      row_annotation_table$max_mean_percent > 70,
    "white",
    "black"
  )

  max_mean_percent_annotation <- ComplexHeatmap::AnnotationFunction(
    which = "row",

    width = grid::unit(
      5.5,
      "mm"
    ),

    var_import = list(
      values = row_annotation_table$max_mean_percent,
      labels = percent_annotation_labels,
      text_colours = percent_annotation_text_colour,
      colour_function = max_mean_percent_color_function,
      font_size = annotation_row_font_size
    ),

    fun = function(index) {

      n_current <- length(index)

      y_positions <- 1 - (
        seq_len(n_current) - 0.5
      ) / n_current

      current_values <- values[index]
      current_labels <- labels[index]
      current_text_colours <- text_colours[index]

      current_fill <- rep(
        "grey90",
        n_current
      )

      finite_values <- is.finite(
        current_values
      )

      current_fill[finite_values] <- colour_function(
        current_values[finite_values]
      )

      grid::grid.rect(
        x = grid::unit(
          0.5,
          "npc"
        ),

        y = grid::unit(
          y_positions,
          "npc"
        ),

        width = grid::unit(
          1,
          "npc"
        ),

        height = grid::unit(
          1 / n_current,
          "npc"
        ),

        gp = grid::gpar(
          fill = current_fill,
          col = NA
        )
      )

      grid::grid.text(
        label = current_labels,

        x = grid::unit(
          0.5,
          "npc"
        ),

        y = grid::unit(
          y_positions,
          "npc"
        ),

        gp = grid::gpar(
