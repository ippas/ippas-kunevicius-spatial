#!/usr/bin/env Rscript

# ==============================================================================
# 03_heatmapLong_effectDonorGroup_FDR005absLog2FC05perCluster_maxPctSeries_4geneSetsFisher19437perCluster_v5.R
#
# Series of five long heatmaps for the main FMT donor-group effect from the
# cluster-specific pseudobulk edgeR two-factor analysis, with additional
# summed GR/MR target-gene repetition annotations from ChEA 2022 and
# one-sided Fisher enrichment tests for four gene sets: GR, MR,
# gr_brain_test and gr_blood_test.
#
# SELECTION
#   FDR < 0.05
#   abs(log2FC) >= 0.5
#
# INPUT
#   Everything is read directly from the RData files generated by the
#   cluster-specific edgeR workflow:
#
#   1. *_edgeRResults.RData
#      - edgeR_perCluster_combinedResults
#      - edgeR_perCluster_testDefinitions
#
#   2. *_edgeRModelObjects.RData
#      - edgeR_perCluster_modelObjects
#      - DGEList for every completed cluster
#      - sample metadata
#      - TMM normalization factors
#
# ROWS
#   Base significant cluster-gene donor-group results satisfying:
#     FDR < 0.05
#     abs(log2FC) >= 0.5
#
#   Five heatmaps are generated from this base result set:
#     1. all      -> no Max mean % filter
#     2. maxPct10 -> Max mean % >= 10
#     3. maxPct15 -> Max mean % >= 15
#     4. maxPct20 -> Max mean % >= 20
#     5. maxPct25 -> Max mean % >= 25
#
#   The same gene can occur more than once when significant in several clusters.
#
# COLUMNS
#   Samples ordered as:
#     Male Neurotypical -> Male ASD -> Female Neurotypical -> Female ASD
#
# HEATMAP VALUES
#   TMM-normalized CPM per sample and cluster
#   -> log2(CPM + 1)
#   -> row-wise Z-score
#   -> clipped to [-2, 2]
#
# ROW CLUSTERING
#   One global hierarchical clustering.
#   Base distance:
#     2 - Pearson correlation
#
#   Rows derived from the same anatomical cluster are made slightly closer,
#   while rows derived from different clusters are made slightly more distant.
#
# RIGHT ANNOTATIONS
#   GR
#     Sum of binary target-gene membership across the three selected GR
#     ChEA 2022 gene sets:
#       0 = absent from all 3 GR sets
#       1 = present in 1/3 GR sets
#       2 = present in 2/3 GR sets
#       3 = present in 3/3 GR sets
#
#   MR
#     Sum of binary target-gene membership across the two selected MR
#     ChEA 2022 gene sets:
#       0 = absent from both MR sets
#       1 = present in 1/2 MR sets
#       2 = present in 2/2 MR sets
#
#   Gene-symbol matching is case-insensitive by converting both heatmap
#   symbols and ChEA symbols to uppercase.
#
# FISHER ENRICHMENT
#   Four gene sets are tested:
#     GR            = union of the three selected GR ChEA 2022 sets
#     MR            = union of the two selected MR ChEA 2022 sets
#     gr_brain_test = manually defined GR brain signature
#     gr_blood_test = manually defined GR blood signature
#
#   For every heatmap variant, one-sided Fisher exact tests
#   (alternative = "greater") are calculated:
#     1. globally for all unique genes displayed on the heatmap
#     2. separately for every source cluster
#
#   Fixed background:
#     19,437 genes for every Fisher contingency table.
#
#   Only global GR/MR Fisher significance is displayed on the heatmap.
#   gr_brain_test, gr_blood_test and all per-cluster Fisher results are written
#   only to TSV files.
#
#   Significance markers:
#     *   p < 0.05
#     **  p < 0.01
#     *** p < 0.001
#
#   Cluster
#     Source Leiden cluster.
#
#   Max mean %
#     Maximum mean percentage of positive spots across:
#       Neurotypical
#       ASD
#
#     For the donor-group main effect, these percentages are already aggregated
#     across sexes in the edgeR result table.
#
#     Percentage is printed directly inside the purple annotation cell.
#     Text colour:
#       <= 70% -> black
#       >  70% -> white
#
#   FDR marker
#       *   FDR < 0.05
#       **  FDR < 0.01
#       *** FDR < 0.001
#
#   |log2FC| marker
#       #   0.5 <= abs(log2FC) < 0.8
#       ##  0.8 <= abs(log2FC) < 1.0
#       ### abs(log2FC) >= 1.0
#
#   n clusters
#     Number of significant source clusters in which the same gene occurs
#     on this heatmap. Genes occurring only once have n clusters = 1.
#
#   Gene symbol
#     Gene symbol with the source-cluster tag, e.g. G3bp1 [C16].
#
# OUTPUT
#   1-5. Five long PDF heatmaps:
#        all, maxPct10, maxPct15, maxPct20, maxPct25.
#   6.   One combined TSV table summarizing the number of displayed
#        cluster-gene results per cluster for every Max mean % variant.
#
# IMPORTANT
#   PDF height is calculated independently for every heatmap and intentionally
#   increases with the number of displayed cluster-gene rows. The unfiltered
#   heatmap can contain >1000 rows and is intended as a technical
#   supplementary/exploratory output rather than a compact figure.
# ==============================================================================

